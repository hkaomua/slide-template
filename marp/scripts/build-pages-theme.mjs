import { copyFile, readFile, writeFile } from 'node:fs/promises';
import './build-theme.mjs';

const root = new URL('../../', import.meta.url);
const css = await readFile(new URL('marp/themes/line-seed.css', root), 'utf8');
const license = await readFile(new URL('fonts/OFL.txt', root), 'utf8');
const header = `/*\nLINE Seed JP font license (applies to embedded font data):\n${license.trim()}\n*/\n`;
await writeFile(new URL('docs/hkaomua.css', root),
  css.replace('/* @theme line-seed */', '/* @theme hkaomua */')
    .replace('/* Generated by npm run theme. Edit line-seed.source.css. */',
      '/* Generated by npm run theme:pages. Edit marp/themes/line-seed.source.css. */\n' + header));
await copyFile(new URL('fonts/OFL.txt', root), new URL('docs/OFL.txt', root));
await copyFile(new URL('LICENSE', root), new URL('docs/LICENSE', root));
console.log('Generated docs/hkaomua.css for GitHub Pages.');
